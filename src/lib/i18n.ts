export const dictionaries: Record<Locale, Record<ArabicDialect, Dict>> = {
  en: { sa: en, eg: en }, // english ignores dialect
  ar: { sa: arSa, eg: arEg },
};

/**
 * Translate a key with optional {placeholder} interpolation.
 */
export function translate(
  key: string,
  locale: Locale,
  dialect: ArabicDialect,
  params?: Record<string, string | number>
): string {
  const dict = dictionaries[locale][dialect] ?? en;
  let str = dict[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}

/** Format a number for the active locale (e.g. 1,234 vs ١٬٢٣٤). */
export function formatNumber(n: number, locale: Locale): string {
  return new Intl.NumberFormat(locale === "ar" ? "ar-EG" : "en-US").format(n);
}

/** Format a price for the active locale. */
export function formatPrice(amount: number, locale: Locale, dialect: ArabicDialect): string {
  const currency = translate("common.currency", locale, dialect, { amount: "" }).trim();
  const symbol = currency || (locale === "ar" ? (dialect === "sa" ? "ر.س" : "ج.م") : "$");
  const formatted = new Intl.NumberFormat(locale === "ar" ? "ar-EG" : "en-US", {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  }).format(amount);
  return locale === "ar" ? `${formatted} ${symbol}` : `${symbol}${formatted}`;
}

/** Format a date for the active locale. */
export function formatDate(date: string | Date, locale: Locale): string {
  const d = typeof date === "string" ? new Date(date) : date;
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-EG" : "en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
  }).format(d);
}

/** Convert minutes to "Xh Ym" or localized. */
export function formatDuration(minutes: number, locale: Locale, dialect: ArabicDialect): string {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  const t = (k: string, p?: Record<string, string | number>) => translate(k, locale, dialect, p);
  if (h === 0) return `${m} ${t("landing.min")}`;
  if (m === 0) return t("card.hours", { n: h });
  return `${t("card.hours", { n: h })} ${m}${t("landing.min")}`;
}
